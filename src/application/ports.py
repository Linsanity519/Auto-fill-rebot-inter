"""Only business data crosses these ports."""
from __future__ import annotations

from typing import Protocol
from ..domain.pricing import PriceItem, PricePlan


class PricePlatform(Protocol):
    def context(self) -> dict: ...
    def discover(self, inputs: dict) -> list[dict]: ...
    def read(self, item: PriceItem) -> str: ...
    def set_state(self, item: PriceItem) -> None: ...


class TaskRepository(Protocol):
    def save_plan(self, plan: PricePlan) -> None: ...
    def plan(self, plan_id: str) -> PricePlan: ...
    def task(self, task_id: str) -> dict: ...
    def results(self, task_id: str) -> list[dict]: ...
    def record(self, task_id: str, item_id: str, status: str, detail: dict) -> None: ...
    def finish(self, task_id: str, status: str, detail: dict) -> None: ...


class ExecutionControl(Protocol):
    def decide(self, task_id: str, item: PriceItem) -> str: ...
