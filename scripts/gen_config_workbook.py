COLS = ["配置项", "必填", "控件类型", "取值 / 选项", "限制", "出现条件", "填写值"]
WIDTHS = [30, 6, 14, 46, 26, 30, 22]


def new_sheet(wb, title):
    ws = wb.create_sheet(title[:31])
    for i, (c, w) in enumerate(zip(COLS, WIDTHS), 1):
        cell = ws.cell(row=1, column=i, value=c)
        cell.font = H_FONT
        cell.fill = H_FILL
        cell.alignment = Alignment(horizontal="center", vertical="center")
        cell.border = BORDER
        ws.column_dimensions[get_column_letter(i)].width = w
    ws.freeze_panes = "A2"
    ws.row_dimensions[1].height = 22
    return ws


def section(ws, r, text):
    ws.cell(row=r, column=1, value=text)
    for c in range(1, len(COLS) + 1):
        cell = ws.cell(row=r, column=c)
        cell.fill = SEC_FILL
        cell.font = SEC_FONT
        cell.border = BORDER
    return r + 1


def row(ws, r, name, req, kind, opts="", limit="", cond=""):
    vals = [name, req, kind, opts, limit, cond, ""]
    for i, v in enumerate(vals, 1):
        cell = ws.cell(row=r, column=i, value=v)
        cell.font = REQ if (i == 1 and req == "是") else BASE
        cell.alignment = Alignment(vertical="top", wrap_text=True)
        cell.border = BORDER
    ws.cell(row=r, column=7).fill = IN_FILL
    return r + 1


