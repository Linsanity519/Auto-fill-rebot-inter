def write_unit_common(ws, r, extras=None, skips=()):
    """extras: 该资源位额外的单元层字段 [(name,req,kind,opts,limit,cond), ...]"""
    for item in UNIT_COMMON:
        if item[0] == "__SEC__":
            r = section(ws, r, "【单元层】" + item[1])
            continue
        if item[0].strip("　└ ") in skips:
            continue
        r = row(ws, r, *item)
    for e in (extras or []):
        r = row(ws, r, *e)
    return r


